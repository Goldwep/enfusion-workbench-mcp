/**
 * Generates the menu-path lists compiled into the shipped Module handler
 * (`wb_module action`, design section 2 and 6; DEC-048 package 3.3):
 *
 *   mod/Scripts/WorkbenchGame/EnfusionMCP/EMCP_WB_ActionAllowList.c
 *       from `data/census/policy.json`: `execute_action.allow_list` (the menu
 *       paths the `action` branch may run, segments joined by "\n"), every
 *       deny-list label (`execute_action.deny_list_seed` plus
 *       `deny_lists.*.labels`) and the refused menu words.
 *
 * DEC-100: `execute_action.allow_list` holds only paths with a passing live
 * result. `execute_action.candidates` (no live result yet) is validated here
 * and NEVER compiled into the shipped file: only the development-only probe
 * pack carries it. A path on `execute_action.dialog_openers` is refused on
 * either list.
 *
 * The validation and the lists are the probe generator's
 * (`scripts/live/gen-probe-allowlist.ts`: `allowListEntries`,
 * `denyLabelList`, `MENU_DENY_WORDS`, `assertNoPersonalData`), so the shipped
 * handler and the probe pack compile the same allow-list from the same policy
 * and refuse the same entries. Deterministic: the same policy gives the same
 * bytes. This script never writes the policy.
 *
 * Usage:
 *   npx tsx scripts/gen-action-allowlist.ts [--policy <policy.json>] [--check]
 *
 * Default: write the file. `--check`: write nothing; exit 1 when the file
 * differs from what the policy generates.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { isMainModule, parseArgs } from "./live/cli.js";
import {
  MENU_DENY_WORDS,
  allowListEntries,
  assertNoPersonalData,
  candidateEntries,
  denyLabelList,
  type ProbePolicy,
} from "./live/gen-probe-allowlist.js";
import { REPO_ROOT } from "./live/paths.js";
import { POLICY_PATH, loadPolicy } from "./live/policy.js";

/** The generated allow-list of the shipped Module handler. */
export const ACTION_ALLOW_LIST_FILE = join(
  REPO_ROOT,
  "mod",
  "Scripts",
  "WorkbenchGame",
  "EnfusionMCP",
  "EMCP_WB_ActionAllowList.c",
);

/** An Enforce string literal; segments are joined with the escape `\n`. */
function lit(segments: string[]): string {
  return `"${segments.join("\\n")}"`;
}

function fillMethod(doc: string, name: string, param: string, values: string[][]): string[] {
  const lines = [
    `\t//! ${doc}`,
    `\tstatic void ${name}(notnull array<string> ${param})`,
    "\t{",
    `\t\t${param}.Clear();`,
  ];
  for (const v of values) lines.push(`\t\t${param}.Insert(${lit(v)});`);
  lines.push("\t}");
  return lines;
}

/** The text of `EMCP_WB_ActionAllowList.c` for a policy. */
export function renderActionAllowList(policy: ProbePolicy): string {
  const paths = allowListEntries(policy);
  // Validated (no overlap with the allow-list, no dialog opener) and deliberately not compiled.
  candidateEntries(policy);
  const deny = denyLabelList(policy);
  const lines = [
    "/**",
    " * EMCP_WB_ActionAllowList.c - GENERATED FILE, do not edit by hand.",
    " *",
    " * Generated by scripts/gen-action-allowlist.ts from data/census/policy.json:",
    ' * execute_action.allow_list (menu paths wb_module action may run, segments joined by "\\n"),',
    " * the deny-list labels (execute_action.deny_list_seed and deny_lists.*.labels) and the refused",
    " * menu words (MENU_DENY_WORDS of scripts/live/gen-probe-allowlist.ts). DEC-100: only paths with",
    " * a passing live result; execute_action.candidates is never compiled here. Change the policy and",
    " * regenerate; --check reports drift.",
    " */",
    "",
    "class EMCP_WB_ActionAllowList",
    "{",
    "\t//! Number of allow-listed menu paths.",
    "\tstatic int Count()",
    "\t{",
    `\t\treturn ${paths.length};`,
    "\t}",
    "",
    ...fillMethod("Allow-listed menu paths, in policy order.", "Paths", "outPaths", paths),
    "",
    ...fillMethod(
      "Deny-list labels: a menu path with a segment that holds one as a run of words is refused even when listed.",
      "DenyLabels",
      "outLabels",
      deny.map((d) => [d]),
    ),
    "",
    ...fillMethod(
      "Refused words: a menu path with a segment that holds one as a word is refused even when listed.",
      "DenyWords",
      "outWords",
      MENU_DENY_WORDS.map((w) => [w]),
    ),
    "}",
    "",
  ];
  return lines.join("\n");
}

/** The generated file and its text for a policy file. */
export function generateActionAllowList(policyPath: string = POLICY_PATH): {
  file: string;
  text: string;
} {
  const policy = loadPolicy(policyPath) as ProbePolicy;
  return {
    file: ACTION_ALLOW_LIST_FILE,
    text: assertNoPersonalData(ACTION_ALLOW_LIST_FILE, renderActionAllowList(policy)),
  };
}

export function main(argv: string[]): number {
  let args;
  try {
    args = parseArgs(argv, ["policy"]);
  } catch (e) {
    console.error(e instanceof Error ? e.message : String(e));
    return 2;
  }
  const check = args.flags.has("check");
  try {
    const o = generateActionAllowList(args.options.policy ?? POLICY_PATH);
    const rel = o.file.slice(REPO_ROOT.length + 1).replace(/\\/g, "/");
    const current = existsSync(o.file) ? readFileSync(o.file, "utf-8") : null;
    if (check) {
      if (current !== o.text) {
        console.log(`DRIFT ${rel}: differs from what the policy generates`);
        return 1;
      }
      console.log(`ok    ${rel}`);
      return 0;
    }
    if (current === o.text) {
      console.log(`unchanged ${rel}`);
    } else {
      writeFileSync(o.file, o.text, "utf-8");
      console.log(`wrote ${rel}`);
    }
    return 0;
  } catch (e) {
    console.error(e instanceof Error ? e.message : String(e));
    return 1;
  }
}

if (isMainModule(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
