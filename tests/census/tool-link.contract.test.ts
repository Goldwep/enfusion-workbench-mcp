const ROOT = join(__dirname, "..", "..");
const code = new Map<string, string>();
function codeOf(file: string): string {
  let t = code.get(file);
  if (t === undefined) {
    t = readFileSync(join(ROOT, file), "utf8");
    if (/\.(c|ts)$/.test(file))
      t = t.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:"'`])\/\/.*$/gm, "$1");
    code.set(file, t);
  }
  return t;
}
const esc = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
function tokenRe(census: string, token: string): RegExp {
  if (token.endsWith("(")) return new RegExp(`\\b${esc(token.slice(0, -1))}\\s*\\(`);
  if (token.startsWith("-")) return new RegExp(`["'\`]${esc(token)}["'\`=\\s]`, "i");
  if (/^(net|plugin):/.test(census.replace(/^census:/, "")))
    return new RegExp(`\\b${esc(token)}\\b`);
  return new RegExp(`["'\`]${esc(token)}(\\.\\.\\.)?["'\`]`);
}

type Entry = { path: string; enumName: string; kind: string };
const catalog = JSON.parse(readFileSync(join(ROOT, "data/census/diag-catalog.json"), "utf8")) as {
  entries: Entry[];
};

const defs = new Map<string, { inputSchema?: unknown }>();
let tmp: string;

beforeAll(() => {
  tmp = mkdtempSync(join(tmpdir(), "emcp-toollink-"));
  vi.stubEnv("ENFUSION_TOOLSET", "all");
  vi.stubEnv("ENFUSION_TOOLS", "");
  const fake = {
    registerTool: (n: string, d: { inputSchema?: unknown }) => void defs.set(n, d),
    registerPrompt: () => undefined,
    registerResource: () => undefined,
  };
  const spy = vi.spyOn(console, "error").mockImplementation(() => undefined);
  const em = process as unknown as NodeJS.EventEmitter;
  const events = ["exit", "SIGINT", "SIGTERM"];
  const before = new Map(events.map((ev) => [ev, em.listeners(ev)]));
  try {
    registerTools(fake as never, {
      ...loadConfig(),
      projectPath: join(tmp, "none-project"),
      corePath: join(tmp, "none-core"),
      workshopPath: undefined,
      projectIndexPath: join(tmp, "index.db"),
    });
  } finally {
    spy.mockRestore();
    for (const ev of events)
      for (const l of em.listeners(ev))
        if (!before.get(ev)!.includes(l)) em.off(ev, l as (...a: unknown[]) => void);
    vi.unstubAllEnvs();
  }
});

afterAll(() => {
  try {
    rmSync(tmp, { recursive: true, force: true });
  } catch {
    /* an open sqlite handle can pin the file on Windows */
  }
});

describe("tool actions name the rows they serve", () => {
  it.each(LINKS)("%s via %s.%s (%s)", (census, tool, action, kind, file, token) => {
    const def = defs.get(tool);
    expect(def, `${tool} is registered`).toBeDefined();
    const raw = def!.inputSchema as { shape?: Record<string, Schema> } & Record<string, Schema>;
    const shape = (raw?.shape ?? raw ?? {}) as Record<string, Schema>;
    const param = ["action", "verb", "scope"].find((p) => shape[p] !== undefined);
    if (param)
      expect(shape[param].safeParse(action).success, `${tool} accepts ${action}`).toBe(true);
    else expect(action).toBe("run");
    if (kind === "source") expect(codeOf(file)).toMatch(tokenRe(census, token));
    if (kind === "diag") {
      const path = census.replace(/^census:diag:/, "");
      const e = catalog.entries.find((x) => x.path === path && x.enumName === token);
      expect(e, `diag-catalog names ${path} as ${token}`).toBeDefined();
      expect(action === "select" ? ["menu"] : ["bool", "value"]).toContain(e!.kind);
    }
  });
});
